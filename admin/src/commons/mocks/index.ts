function loop(
  cx: number,
  cy: number,
  rx: number,
  ry: number,
  wobble: number
): PathPoint[] {
  return Array.from({ length: 33 }, (_, i) => {
    const t = (i / 32) * Math.PI * 2
    const r = 1 + Math.sin(t * 3) * wobble
    return [cx + Math.cos(t) * rx * r, cy + Math.sin(t) * ry * r]
  })
}

function river(amplitude: number, waves: number): PathPoint[] {
  return Array.from({ length: 25 }, (_, i) => {
    const x = 0.08 + (i / 24) * 0.84
    return [x, 0.5 + Math.sin((i / 24) * Math.PI * waves) * amplitude]
  })
}

